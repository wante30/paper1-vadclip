"""Generate paper/numbers.tex: LaTeX macros for every number quoted in prose.

Reads only evidence/*.csv (built by build_ledger.py / length_stats.py) and the
experiment-repo records listed below. No number in sections/*.tex is typed by hand.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EV = ROOT / "evidence"
EXP = Path(r"C:\Projects\baseline-first\vadclip_method_stage11_isolated_semantic_posttrain")


def read_csv(name):
    with (EV / name).open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def delta(ds, metric, a, b):
    for d in read_csv("paired_deltas.csv"):
        if (d["dataset"], d["metric"], d["a"], d["b"]) == (ds, metric, a, b):
            return d
    raise KeyError((ds, metric, a, b))


def signed(x, nd=2):
    return f"{float(x):+.{nd}f}"


def main():
    macros = {}
    lengths = {r["split"]: r for r in read_csv("length_stats.csv")}
    macros["ucfTrainAvgFrac"] = f"{float(lengths['UCF_train']['frac_len_gt_256']) * 100:.1f}"
    macros["xdTrainAvgFrac"] = f"{float(lengths['XD_train']['frac_len_gt_256']) * 100:.1f}"
    macros["ucfBinSize"] = f"{float(lengths['UCF_train']['mean_bin_size_when_averaged']):.1f}"
    macros["xdBinSize"] = f"{float(lengths['XD_train']['mean_bin_size_when_averaged']):.1f}"

    comp = json.loads((EXP / "STAGE14_SEED236_COMPLETION.json").read_text(encoding="utf-8-sig"))
    macros["pvrParams"] = f"{int(comp['R2_ucf_seed236_POST']['added_trainable_params']):,}".replace(",", "{,}")
    xdg = json.loads((EXP / "XD_PROTECTED_G_3SEED_COMPARISON.json").read_text(encoding="utf-8-sig"))
    macros["mlpOneParams"] = f"{int(xdg['protocol']['trainable_param_count']):,}".replace(",", "{,}")

    macros["fullGXdApTwo"] = signed(delta("XD", "AP2", "clean:fullG", "clean:AE")["mean_pp"])
    macros["fullGUcfAucOne"] = signed(delta("UCF", "AUC1", "clean:fullG", "clean:AE")["mean_pp"])

    cx = {(r["dataset"], r["arm"]): r for r in read_csv("complexity.csv")}
    for ds, tag in (("UCF", "Ucf"), ("XD", "Xd")):
        base, final = cx[(ds, "B0")], cx[(ds, "Final")]
        lb, lf = float(base["latency_ms_median"]), float(final["latency_ms_median"])
        macros[f"cx{tag}LatBase"] = f"{lb:.1f}"
        macros[f"cx{tag}LatOurs"] = f"{lf:.1f}"
        macros[f"cx{tag}LatRel"] = f"{(lf / lb - 1) * 100:.1f}"
        macros[f"cx{tag}MemDelta"] = f"{float(final['peak_alloc_mb']) - float(base['peak_alloc_mb']):.0f}"
    macros["cxGpu"] = cx[("UCF", "B0")]["gpu"]

    lines = ["% Auto-generated by scripts/make_numbers.py. Do not edit by hand."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(macros.items())]
    (ROOT / "paper" / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    for k, v in sorted(macros.items()):
        print(f"{k} = {v}")


if __name__ == "__main__":
    main()
